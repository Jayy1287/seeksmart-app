import type { Metadata } from "next";
import type { ReactNode } from "react";
import Link from "next/link";
import { redirect } from "next/navigation";
import {
  ArrowRight,
  BarChart3,
  CheckCircle2,
  ClipboardList,
  Gauge,
  Lightbulb,
  ShieldAlert,
  Target
} from "lucide-react";
import type { LucideIcon } from "lucide-react";
import { AuditAnalyticsEvent } from "@/features/audit/audit-analytics";
import { ToolLogo } from "@/features/tools/tool-logo";
import {
  budgetRangeLabel,
  companySizeLabel,
  dataReadinessLabel,
  dataSensitivityLabel,
  decisionOwnerLabel,
  approvalModeLabel,
  goalLabel,
  integrationNeedLabel,
  painPointLabel,
  parseAuditInput,
  technicalComfortLabel,
  urgencyLabel,
  workflowVolumeLabel,
  workflowMaturityLabel
} from "@/server/recommendations/input";
import { getAuditDataset } from "@/server/recommendations/queries";
import { scoreAudit } from "@/server/recommendations/scoring";
import type { AuditOpportunityRecommendation } from "@/shared/recommendations/audit";

export const dynamic = "force-dynamic";

export const metadata: Metadata = {
  title: "AI Audit Results",
  description:
    "View your rules-based AI audit result with ranked opportunities and tool shortlists.",
  alternates: {
    canonical: "/audit/results"
  }
};

type AuditResultsPageProps = {
  searchParams: Promise<Record<string, string | string[] | undefined>>;
};

export default async function AuditResultsPage({
  searchParams
}: AuditResultsPageProps) {
  const params = await searchParams;
  const input = parseAuditInput(params);

  if (!input) {
    redirect("/audit/questions");
  }

  const dataset = await getAuditDataset();
  const result = scoreAudit(input, dataset);

  return (
    <main className="page-shell">
      <AuditAnalyticsEvent
        event="audit_results_viewed"
        properties={{
          budgetRange: input.budgetRange,
          companySize: input.companySize,
          dataSensitivity: input.dataSensitivity,
          topOpportunity: result.topOpportunities[0]?.slug ?? "none"
        }}
      />
      <div className="app-container">
        <section className="border-b border-line/50 pb-10">
          <div className="grid gap-8 lg:grid-cols-[1fr_360px] lg:items-end">
            <div>
              <p className="eyebrow">
                <BarChart3 aria-hidden="true" size={14} />
                Audit result
              </p>
              <h1 className="mt-5 max-w-4xl text-5xl font-semibold leading-[0.98] md:text-6xl">
                Your AI pilot brief.
              </h1>
              <p className="mt-4 max-w-2xl text-lg leading-8 text-ink/68">
                {result.summary.executiveBrief} This result is generated by{" "}
                {result.version}, using deterministic scoring over SeekSmart
                taxonomy data.
              </p>
            </div>
            <div className="metric-tile rounded-2xl p-5">
              <p className="text-sm font-semibold text-accent">
                Executive recommendation
              </p>
              <p className="mt-2 text-xl font-semibold leading-7">
                {result.summary.firstWorkflow}
              </p>
            </div>
          </div>
        </section>

        <section className="mt-6 grid gap-4 md:grid-cols-4">
          <ContextTile label="Industry" value={result.summary.industryName} />
          <ContextTile
            label="Function"
            value={result.summary.businessFunctionName}
          />
          <ContextTile label="Team size" value={companySizeLabel(input.companySize)} />
          <ContextTile label="Readiness" value={`${result.readiness.level} (${result.readiness.score})`} />
        </section>

        <section className="section-band -mx-4 mt-6 px-4 py-8 sm:-mx-6 sm:px-6 lg:-mx-8 lg:px-8">
          <div className="grid gap-6 lg:grid-cols-[0.85fr_1.15fr]">
            <div>
              <p className="text-sm font-extrabold uppercase text-accent">
                Pilot plan
              </p>
              <h2 className="mt-2 text-3xl font-semibold">
                {result.pilotPlan.title}
              </h2>
              <p className="mt-3 leading-7 text-ink/62">
                {result.summary.automationPosture}
              </p>
            </div>
            <div className="grid gap-3 md:grid-cols-3">
              <PlanTile label="Owner" value={result.pilotPlan.owner} />
              <PlanTile label="Timeline" value={result.pilotPlan.timeline} />
              <PlanTile
                label="Success metric"
                value={result.pilotPlan.successMetric}
              />
            </div>
          </div>
          <div className="mt-5 grid gap-3 md:grid-cols-2">
            <PlanTile
              label="Baseline question"
              value={result.pilotPlan.baselineQuestion}
            />
            <PlanTile label="Pilot target" value={result.pilotPlan.target} />
          </div>
          <div className="mt-7 grid gap-6 lg:grid-cols-3">
            <PlanList
              icon={ClipboardList}
              title="Week-one actions"
              items={result.pilotPlan.weekOneActions}
            />
            <PlanList
              icon={ShieldAlert}
              title="Guardrails"
              items={result.pilotPlan.guardrails}
            />
            <PlanList
              icon={Lightbulb}
              title="Expand only if"
              items={result.pilotPlan.expansionCriteria}
            />
          </div>
        </section>

        <section className="mt-8 grid gap-6 lg:grid-cols-[1fr_360px]">
          <div className="grid gap-5">
            {result.topOpportunities.map((opportunity, index) => (
              <OpportunityResult
                index={index + 1}
                key={opportunity.id}
                opportunity={opportunity}
              />
            ))}
          </div>

          <aside className="grid h-fit gap-5">
            <section className="surface-strong rounded-xl p-5">
              <div className="flex items-center justify-between gap-4">
                <div>
                  <p className="text-xs font-semibold uppercase text-ink/45">
                    Readiness assessment
                  </p>
                  <h2 className="mt-1 text-xl font-semibold">
                    {result.readiness.level}
                  </h2>
                </div>
                <div className="metric-tile rounded-xl px-4 py-3 text-center">
                  <p className="text-xs font-semibold uppercase text-ink/45">
                    Score
                  </p>
                  <p className="mt-1 text-2xl font-semibold">
                    {result.readiness.score}
                  </p>
                </div>
              </div>
              <p className="mt-3 text-sm leading-6 text-ink/62">
                {result.readiness.summary}
              </p>
              <ReadinessList title="Strengths" items={result.readiness.strengths} />
              <ReadinessList title="Watch-outs" items={result.readiness.risks} />
            </section>

            <section className="surface-panel rounded-xl p-5">
              <h2 className="text-xl font-semibold">Audit context</h2>
              <div className="mt-4 grid gap-2 text-sm">
                <AuditFact
                  label="Goals"
                  value={input.goals.map(goalLabel).join(", ")}
                />
                <AuditFact
                  label="Pain points"
                  value={input.painPoints.map(painPointLabel).join(", ")}
                />
                <AuditFact
                  label="Budget"
                  value={budgetRangeLabel(input.budgetRange)}
                />
                <AuditFact
                  label="Technical comfort"
                  value={technicalComfortLabel(input.technicalComfort)}
                />
                <AuditFact
                  label="Data sensitivity"
                  value={dataSensitivityLabel(input.dataSensitivity)}
                />
                <AuditFact
                  label="Workflow volume"
                  value={workflowVolumeLabel(input.workflowVolume)}
                />
                <AuditFact
                  label="Data readiness"
                  value={dataReadinessLabel(input.dataReadiness)}
                />
                <AuditFact
                  label="Decision owner"
                  value={decisionOwnerLabel(input.decisionOwner)}
                />
                <AuditFact
                  label="Workflow maturity"
                  value={workflowMaturityLabel(input.workflowMaturity)}
                />
                <AuditFact
                  label="Approval"
                  value={approvalModeLabel(input.approvalMode)}
                />
                <AuditFact
                  label="Systems"
                  value={
                    input.integrationNeeds.length > 0
                      ? input.integrationNeeds.map(integrationNeedLabel).join(", ")
                      : "No specific systems selected"
                  }
                />
                <AuditFact label="Urgency" value={urgencyLabel(input.urgency)} />
              </div>
            </section>

            <section className="surface-panel rounded-xl p-5">
              <div className="flex items-center gap-2">
                <ShieldAlert aria-hidden="true" className="text-accent" size={20} />
                <h2 className="text-xl font-semibold">Caution</h2>
              </div>
              <p className="mt-3 text-sm leading-6 text-ink/62">
                {result.summary.overallCaution}
              </p>
            </section>

            <section className="surface-strong rounded-xl p-5">
              <h2 className="text-xl font-semibold">Decision checklist</h2>
              <div className="mt-4 grid gap-3">
                {result.nextStepChecklist.map((item) => (
                  <div className="flex gap-3 text-sm leading-6" key={item}>
                    <CheckCircle2
                      aria-hidden="true"
                      className="mt-0.5 shrink-0 text-accent"
                      size={16}
                    />
                    <span>{item}</span>
                  </div>
                ))}
              </div>
            </section>

            <Link className="secondary-button min-h-12" href="/audit/questions">
              Adjust answers
            </Link>
          </aside>
        </section>
      </div>
    </main>
  );
}

function OpportunityResult({
  index,
  opportunity
}: {
  index: number;
  opportunity: AuditOpportunityRecommendation;
}) {
  return (
    <article className="surface-panel overflow-hidden rounded-2xl">
      <div className="border-b border-line bg-white/72 p-5 md:p-6">
        <div className="flex flex-col gap-4 md:flex-row md:items-start md:justify-between">
        <div>
          <div className="flex flex-wrap items-center gap-2">
            <span className="status-pill">#{index}</span>
            <span className="status-pill">{opportunity.fitLabel}</span>
            {opportunity.businessFunctionName ? (
              <span className="status-pill">
                {opportunity.businessFunctionName}
              </span>
            ) : null}
          </div>
          <h2 className="mt-4 text-2xl font-semibold">{opportunity.name}</h2>
          <p className="mt-3 max-w-3xl leading-7 text-ink/65">
            {opportunity.expectedBenefit ??
              opportunity.description ??
              "A mapped business opportunity from the SeekSmart taxonomy."}
          </p>
        </div>
        <div className="metric-tile min-w-32 rounded-xl p-4 text-center">
          <p className="text-sm font-semibold text-accent">Fit score</p>
          <p className="mt-1 text-4xl font-semibold">{opportunity.score}</p>
          <p className="mt-1 text-xs font-medium text-ink/45">Directional</p>
        </div>
      </div>
      </div>

      <div className="grid gap-3 p-5 md:grid-cols-4 md:p-6">
        <ScoreTile
          icon={Target}
          label="Impact"
          value={opportunity.impactScore}
        />
        <ScoreTile icon={Gauge} label="Effort fit" value={opportunity.effortScore} />
        <ScoreTile
          icon={ShieldAlert}
          label="Risk fit"
          value={opportunity.riskScore}
        />
        <ScoreTile
          icon={BarChart3}
          label="Confidence"
          value={opportunity.confidenceScore}
        />
      </div>

      <div className="grid gap-5 border-t border-line p-5 lg:grid-cols-2 md:p-6">
        <section>
          <h3 className="font-semibold">Why this ranked here</h3>
          <div className="mt-3 grid gap-2">
            {opportunity.reasons.map((reason) => (
              <ReasonItem key={reason}>{reason}</ReasonItem>
            ))}
          </div>
        </section>
        <section>
          <h3 className="font-semibold">Use-case path</h3>
          <div className="mt-3 grid gap-2">
            {opportunity.useCases.map((useCase) => (
              <Link
                className="rounded-lg border border-line bg-surface/72 p-3 transition hover:border-accent"
                href={`/use-cases/${useCase.slug}`}
                key={useCase.id}
              >
                <div className="flex items-center justify-between gap-3">
                  <span className="font-medium">{useCase.name}</span>
                  <ArrowRight aria-hidden="true" size={14} />
                </div>
                <p className="mt-1 text-xs leading-5 text-ink/55">
                  {useCase.timeToValue ?? "Time to value depends on setup"} ·{" "}
                  {useCase.effortLevel} effort · {useCase.riskLevel} risk
                </p>
              </Link>
            ))}
          </div>
        </section>
      </div>

      {opportunity.cautions.length > 0 ? (
        <div className="mx-5 rounded-xl border border-signal/30 bg-signal/10 p-4 text-sm leading-6 text-ink/70 md:mx-6">
          <p className="font-semibold text-signal">Review before piloting</p>
          <ul className="mt-2 grid gap-1">
            {opportunity.cautions.map((caution) => (
              <li key={caution}>{caution}</li>
            ))}
          </ul>
        </div>
      ) : null}

      <section className="border-t border-line p-5 md:p-6">
        <h3 className="font-semibold">Tool shortlist</h3>
        <div className="mt-3 grid gap-3 md:grid-cols-3">
          {opportunity.tools.map((tool) => (
            <Link
              className="rounded-xl border border-line bg-surface/72 p-4 transition hover:-translate-y-0.5 hover:border-accent"
              href={`/tools/${tool.slug}`}
              key={tool.id}
            >
              <div className="flex items-start justify-between gap-3">
                <div className="flex min-w-0 items-start gap-3">
                  <ToolLogo logoUrl={tool.logoUrl} name={tool.name} size="sm" />
                  <div className="min-w-0">
                    <h4 className="truncate font-semibold">{tool.name}</h4>
                    <p className="mt-1 text-xs text-ink/50">{tool.categoryName}</p>
                  </div>
                </div>
                <span className="rounded-lg bg-ink px-2 py-1 text-xs font-semibold text-paper">
                  {tool.fitScore}
                </span>
              </div>
              <p className="mt-3 text-sm leading-6 text-ink/62">{tool.reason}</p>
              <p className="mt-3 text-xs font-semibold uppercase text-accent">
                {tool.pricingType}
                {tool.hasFreePlan ? " · Free plan" : ""}
              </p>
            </Link>
          ))}
        </div>
      </section>
    </article>
  );
}

function ContextTile({ label, value }: { label: string; value: string }) {
  return (
    <div className="metric-tile rounded-xl p-4">
      <p className="text-xs font-semibold uppercase text-ink/48">{label}</p>
      <p className="mt-2 font-semibold">{value}</p>
    </div>
  );
}

function PlanTile({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-2xl border border-line/55 bg-white/42 p-4 shadow-[0_18px_54px_rgb(38_78_162/0.055)] backdrop-blur">
      <p className="text-xs font-semibold uppercase text-ink/48">{label}</p>
      <p className="mt-2 font-semibold leading-6">{value}</p>
    </div>
  );
}

function PlanList({
  icon: Icon,
  items,
  title
}: {
  icon: LucideIcon;
  items: string[];
  title: string;
}) {
  return (
    <section className="rounded-2xl border border-line/55 bg-white/42 p-5 shadow-[0_18px_54px_rgb(38_78_162/0.055)] backdrop-blur">
      <div className="flex items-center gap-2">
        <Icon aria-hidden="true" className="text-accent" size={19} />
        <h3 className="font-semibold">{title}</h3>
      </div>
      <div className="mt-4 grid gap-3">
        {items.map((item) => (
          <div className="flex gap-3 text-sm leading-6" key={item}>
            <CheckCircle2
              aria-hidden="true"
              className="mt-0.5 shrink-0 text-accent"
              size={15}
            />
            <span>{item}</span>
          </div>
        ))}
      </div>
    </section>
  );
}

function ReadinessList({ items, title }: { items: string[]; title: string }) {
  if (items.length === 0) {
    return null;
  }

  return (
    <div className="mt-4">
      <p className="text-xs font-semibold uppercase text-ink/45">{title}</p>
      <div className="mt-2 grid gap-2">
        {items.map((item) => (
          <div className="flex gap-2 text-sm leading-6" key={item}>
            <CheckCircle2
              aria-hidden="true"
              className="mt-0.5 shrink-0 text-accent"
              size={14}
            />
            <span>{item}</span>
          </div>
        ))}
      </div>
    </div>
  );
}

function AuditFact({ label, value }: { label: string; value: string }) {
  return (
    <div className="rounded-lg border border-line bg-surface/70 p-3">
      <p className="text-xs font-semibold uppercase text-ink/45">{label}</p>
      <p className="mt-1 font-medium leading-6">{value}</p>
    </div>
  );
}

function ScoreTile({
  icon: Icon,
  label,
  value
}: {
  icon: LucideIcon;
  label: string;
  value: number;
}) {
  return (
    <div className="metric-tile rounded-xl p-4">
      <div className="flex items-center justify-between gap-2">
        <Icon aria-hidden="true" className="text-accent" size={18} />
        <span className="font-semibold">{value}</span>
      </div>
      <p className="mt-2 text-xs font-semibold uppercase text-ink/48">{label}</p>
    </div>
  );
}

function ReasonItem({ children }: { children: ReactNode }) {
  return (
    <div className="flex gap-3 rounded-lg border border-line bg-surface/72 p-3 text-sm leading-6">
      <CheckCircle2
        aria-hidden="true"
        className="mt-0.5 shrink-0 text-accent"
        size={15}
      />
      <span>{children}</span>
    </div>
  );
}
